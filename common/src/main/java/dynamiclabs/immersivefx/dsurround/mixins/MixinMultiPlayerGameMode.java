package dynamiclabs.immersivefx.dsurround.mixins;

import dynamiclabs.immersivefx.specialfx.DropItemSounds;
import net.minecraft.client.multiplayer.MultiPlayerGameMode;
import net.minecraft.client.player.LocalPlayer;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(MultiPlayerGameMode.class)
public abstract class MixinMultiPlayerGameMode {

    @Inject(method = "dropItem(Lnet/minecraft/client/player/LocalPlayer;Z)V", at = @At("HEAD"))
    private void dsurround_dropItem(final LocalPlayer player, final boolean all, final CallbackInfo ci) {
        if (!player.getInventory().getSelectedItem().isEmpty()) {
            DropItemSounds.onLocalDrop(player);
        }
    }
}
